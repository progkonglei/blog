/**
 * 文档沉淀（Doc Deposit）
 *
 * 每次会话 / 每一轮结束后，把可读总结写入仓库内 `docs/runs/`，
 * 与 `.sessions/`（gitignore）互补：日志留本地，文档可提交、可复盘。
 *
 * 目录结构：
 *   docs/runs/
 *     INDEX.md                         # 全部会话索引（自动维护）
 *     LATEST.md                        # 最近一次会话快照
 *     2026-07-22_a1b2c3d4.md           # 单次完整会话
 *     2026-07-22_a1b2c3d4/
 *       turn-01.md                     # 单轮沉淀
 */
import { appendFile, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

export type DepositMeta = {
  sessionId: string;
  cwd: string;
  permissionMode?: string;
  startedAt?: string;
};

export type DepositTurn = {
  turn: number;
  oneLineSummary: string;
  markdown: string;
  user: string;
  tools: string[];
  llmCalls: number;
  durationMs?: number;
};

export type DocDepositOptions = {
  /** 一般为 <project>/docs/runs */
  runsDir: string;
  enabled?: boolean;
};

export class DocDeposit {
  readonly runsDir: string;
  readonly enabled: boolean;
  private sessionFile = "";
  private sessionDir = "";
  private slug = "";

  constructor(opts: DocDepositOptions) {
    this.runsDir = opts.runsDir;
    this.enabled = opts.enabled ?? process.env.AGENT_DOC_DEPOSIT !== "0";
  }

  /** 会话开始时确定文件名 */
  async begin(meta: DepositMeta): Promise<string | null> {
    if (!this.enabled) return null;
    await mkdir(this.runsDir, { recursive: true });
    const day = new Date().toISOString().slice(0, 10);
    const short = String(meta.sessionId).replace(/-/g, "").slice(0, 8);
    this.slug = `${day}_${short}`;
    this.sessionFile = path.join(this.runsDir, `${this.slug}.md`);
    this.sessionDir = path.join(this.runsDir, this.slug);
    await mkdir(this.sessionDir, { recursive: true });

    const header = [
      `# 会话沉淀 ${this.slug}`,
      "",
      `> 自动生成 · session \`${meta.sessionId}\``,
      "",
      `| 项 | 值 |`,
      `|---|---|`,
      `| 日期 | ${day} |`,
      `| cwd | ${meta.cwd} |`,
      `| mode | ${meta.permissionMode ?? ""} |`,
      `| 开始 | ${meta.startedAt ?? new Date().toISOString()} |`,
      "",
      "## 各轮摘要",
      "",
      "_（进行中，每轮结束后追加）_",
      "",
    ].join("\n");
    await writeFile(this.sessionFile, header, "utf8");
    return this.sessionFile;
  }

  /** 每轮结束：沉淀 turn 文档，并刷新会话稿 */
  async depositTurn(turn: DepositTurn, allTurns: DepositTurn[]): Promise<void> {
    if (!this.enabled || !this.sessionFile) return;
    const id = String(turn.turn).padStart(2, "0");
    const turnPath = path.join(this.sessionDir, `turn-${id}.md`);
    await writeFile(turnPath, turn.markdown, "utf8");

    // 重写会话稿（含最新索引表）
    await this.rewriteSessionDoc(allTurns, false);
  }

  /** 会话结束：定稿 + 更新 INDEX / LATEST */
  async finalize(meta: DepositMeta, allTurns: DepositTurn[], sessionBody?: string): Promise<string | null> {
    if (!this.enabled || !this.sessionFile) return null;
    await this.rewriteSessionDoc(allTurns, true, sessionBody);

    const latest = [
      `# 最近一次会话`,
      "",
      `来源: [\`${this.slug}.md\`](./${this.slug}.md)`,
      "",
      await readFile(this.sessionFile, "utf8"),
    ].join("\n");
    await writeFile(path.join(this.runsDir, "LATEST.md"), latest, "utf8");
    await this.upsertIndex(meta, allTurns);
    return this.sessionFile;
  }

  get sessionDocPath(): string | undefined {
    return this.sessionFile || undefined;
  }

  private async rewriteSessionDoc(allTurns: DepositTurn[], ended: boolean, extra?: string): Promise<void> {
    const lines: string[] = [
      `# 会话沉淀 ${this.slug}`,
      "",
      `> 自动生成 · ${ended ? "已结束" : "进行中"}`,
      "",
      "## 一句话索引",
      "",
    ];
    if (!allTurns.length) {
      lines.push("_尚无完成的轮次_");
    } else {
      for (const t of allTurns) {
        lines.push(`- **Turn ${t.turn}**: ${t.oneLineSummary}`);
      }
    }
    lines.push("", "## 轮次详情", "");
    for (const t of allTurns) {
      const id = String(t.turn).padStart(2, "0");
      lines.push(`### Turn ${id}`);
      lines.push("");
      lines.push(`- 用户: ${clip(t.user, 120)}`);
      lines.push(`- 工具: ${t.tools.length ? t.tools.join(", ") : "无"}`);
      lines.push(`- LLM 调用: ${t.llmCalls}`);
      if (t.durationMs != null) lines.push(`- 耗时: ${t.durationMs} ms`);
      lines.push(`- 详情: [\`turn-${id}.md\`](./${this.slug}/turn-${id}.md)`);
      lines.push("");
    }
    if (extra) {
      lines.push("## 会话总览", "", extra, "");
    }
    lines.push("---", "");
    lines.push(`_generated by agent-cli DocDeposit_`);
    lines.push("");
    await writeFile(this.sessionFile, lines.join("\n"), "utf8");
  }

  private async upsertIndex(meta: DepositMeta, allTurns: DepositTurn[]): Promise<void> {
    const indexPath = path.join(this.runsDir, "INDEX.md");
    let prev = "";
    try {
      prev = await readFile(indexPath, "utf8");
    } catch {
      prev = [
        `# 会话文档索引`,
        "",
        `每次运行自动追加。详情见各 \`YYYY-MM-DD_xxxxxxxx.md\`。`,
        "",
        `| 时间 | Session | Turns | 摘要 | 文件 |`,
        `|---|---|---|---|---|`,
        "",
      ].join("\n");
    }

    const ts = new Date().toISOString();
    const summary = allTurns.map((t) => t.oneLineSummary).join(" / ") || "(empty)";
    const row = `| ${ts.slice(0, 19)} | \`${String(meta.sessionId).slice(0, 8)}\` | ${allTurns.length} | ${clip(summary, 80)} | [\`${this.slug}.md\`](./${this.slug}.md) |`;

    // 插到表头后第一行（最新在上）
    const marker = `|---|---|---|---|---|`;
    if (prev.includes(marker)) {
      prev = prev.replace(marker, `${marker}\n${row}`);
    } else {
      prev = `${prev.trimEnd()}\n${row}\n`;
    }
    await writeFile(indexPath, prev, "utf8");

    // 追加一条到 changelog 风格流水
    await appendFile(
      path.join(this.runsDir, "HISTORY.jsonl"),
      `${JSON.stringify({
        ts,
        sessionId: meta.sessionId,
        slug: this.slug,
        turns: allTurns.length,
        oneLiners: allTurns.map((t) => t.oneLineSummary),
      })}\n`,
      "utf8",
    );
  }
}

export function resolveRunsDir(cwd: string): string {
  const override = process.env.AGENT_DOC_DIR;
  if (override) return override;
  // 优先写到 agent-cli/docs/runs（若 cwd 就是包根或子目录）
  return path.join(cwd, "docs", "runs");
}

function clip(s: string, n: number): string {
  const t = s.replace(/\s+/g, " ").trim();
  return t.length <= n ? t : `${t.slice(0, n - 1)}…`;
}
